#!/usr/bin/env bash
# Generates the seccomp tables from kernel headers: gen-syscalls.sh denied-syscalls.txt > syscalls.h
set -euo pipefail
list=$1
h64=/usr/include/asm/unistd_64.h
h32=/usr/include/asm/unistd_32.h
[[ -r $h64 && -r $h32 ]] || { echo "error: kernel headers missing ($h64, $h32)" >&2; exit 1; }

nr() { awk -v name="__NR_$2" '$1 == "#define" && $2 == name { print $3; exit }' "$1"; }

table() {
    local header=$1 name n
    while IFS= read -r name; do
        name=${name%%#*}; name=${name//[[:space:]]/}
        [[ -n $name ]] || continue
        n=$(nr "$header" "$name")
        [[ -n $n ]] && printf '    %s, /* %s */\n' "$n" "$name"
    done < "$list"
}

required() {
    local n; n=$(nr "$1" "$2")
    [[ -n $n ]] || { echo "error: __NR_$2 not found in $1" >&2; exit 1; }
    printf '#define %s %s\n' "$3" "$n"
}

printf '/* Generated by gen-syscalls.sh; do not edit. */\n'
printf 'static const unsigned int denied64[] = {\n'; table "$h64"; printf '};\n'
printf 'static const unsigned int denied32[] = {\n'; table "$h32"; printf '};\n'
required "$h64" clone  NR64_CLONE
required "$h64" clone3 NR64_CLONE3
required "$h64" socket NR64_SOCKET
required "$h64" ioctl  NR64_IOCTL
required "$h32" clone  NR32_CLONE
required "$h32" clone3 NR32_CLONE3
required "$h32" socket NR32_SOCKET
required "$h32" ioctl  NR32_IOCTL
